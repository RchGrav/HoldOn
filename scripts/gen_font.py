#!/usr/bin/env python3
"""Generate src/screen/font_data.h from a GNU Unifont .hex file.

Usage: python3 -I scripts/gen_font.py unifont-16.0.04.hex.gz > src/screen/font_data.h

Keeps the blocks terminal programs draw with (Latin, Greek, Cyrillic,
punctuation, arrows, math, technical, box drawing, blocks, shapes, symbols,
dingbats, Braille, kana, fullwidth forms). Glyphs are 8x16 (16 bytes) or
16x16 (32 bytes, wide). Anything absent renders as a hollow box.
"""
import gzip
import sys

RANGES = [
    (0x0020, 0x007E), (0x00A0, 0x02FF), (0x0300, 0x036F), (0x0370, 0x03FF),
    (0x0400, 0x04FF), (0x2000, 0x206F), (0x2070, 0x209F), (0x20A0, 0x20CF),
    (0x2100, 0x214F), (0x2150, 0x218F), (0x2190, 0x21FF), (0x2200, 0x22FF),
    (0x2300, 0x23FF), (0x2400, 0x243F), (0x2460, 0x24FF), (0x2500, 0x257F),
    (0x2580, 0x259F), (0x25A0, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF),
    (0x27C0, 0x27FF), (0x2800, 0x28FF), (0x2900, 0x297F), (0x2980, 0x29FF),
    (0x2B00, 0x2BFF), (0x3000, 0x303F), (0x3040, 0x30FF), (0xFF00, 0xFFEF),
    (0xFFFD, 0xFFFD),
]


def wanted(cp):
    return any(lo <= cp <= hi for lo, hi in RANGES)


def main():
    path = sys.argv[1]
    opener = gzip.open if path.endswith(".gz") else open
    glyphs = []
    with opener(path, "rt") as f:
        for line in f:
            cp_hex, _, bits = line.strip().partition(":")
            cp = int(cp_hex, 16)
            if wanted(cp) and len(bits) in (32, 64):
                glyphs.append((cp, bytes.fromhex(bits)))
    glyphs.sort()
    out = sys.stdout
    out.write("/* Generated by scripts/gen_font.py from GNU Unifont (SIL OFL 1.1; see\n"
              " * third_party/unifont/). Do not edit. */\n")
    out.write("#define HOLD_FONT_GLYPHS %d\n" % len(glyphs))
    out.write("static const uint16_t font_cp[HOLD_FONT_GLYPHS] = {\n")
    for i in range(0, len(glyphs), 12):
        out.write("    " + ", ".join("0x%04x" % g[0] for g in glyphs[i:i + 12]) + ",\n")
    out.write("};\n/* offset into font_bits; bit 31 marks a 16-pixel-wide glyph */\n")
    out.write("static const uint32_t font_off[HOLD_FONT_GLYPHS] = {\n")
    offs, pos = [], 0
    for cp, b in glyphs:
        offs.append(pos | (0x80000000 if len(b) == 32 else 0))
        pos += len(b)
    for i in range(0, len(offs), 8):
        out.write("    " + ", ".join("0x%08xu" % o for o in offs[i:i + 8]) + ",\n")
    out.write("};\nstatic const unsigned char font_bits[%d] = {\n" % pos)
    blob = b"".join(g[1] for g in glyphs)
    for i in range(0, len(blob), 16):
        out.write("    " + ",".join("0x%02x" % x for x in blob[i:i + 16]) + ",\n")
    out.write("};\n")


main()
